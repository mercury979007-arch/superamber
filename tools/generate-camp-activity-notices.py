#!/usr/bin/env python3
"""Generate camp activity reminder data for the summer camp report."""

from __future__ import annotations

import argparse
import json
import re
from pathlib import Path

from openpyxl import load_workbook


STAGE_TO_MAJOR = {
    "L0营": "L0",
    "L1小龄营": "L1小",
    "L1大龄营": "L1大",
    "L2营": "L2",
    "L3营": "L3",
    "L4/5营": "L4",
    "S营": "S",
}

NOTICE_ALIASES = {
    "Happy": "Happy集体活动",
}


def normalize_date(value: object) -> str:
    text = str(value or "").strip()
    match = re.match(r"(\d{4})/(\d{1,2})/(\d{1,2})", text)
    if not match:
        raise ValueError(f"Unsupported date value: {text!r}")
    year, month, day = match.groups()
    return f"{int(year):04d}-{int(month):02d}-{int(day):02d}"


def make_tomorrow_notice(text: object) -> str:
    clean = str(text or "").strip()
    return clean.replace("今天苦令营将迎来", "明天苦令营将迎来")


def read_notice_library(workbook_path: Path) -> dict[str, str]:
    workbook = load_workbook(workbook_path, read_only=True, data_only=True)
    sheet = workbook["通知话术库"]
    notices: dict[str, str] = {}
    for row in sheet.iter_rows(min_row=2, values_only=True):
        name, _activity_type, _opening, _intro, _reminder, full_notice = row[:6]
        if not name or not full_notice:
            continue
        notices[str(name).strip()] = make_tomorrow_notice(full_notice)
    return notices


def read_activity_entries(workbook_path: Path) -> list[dict[str, str]]:
    workbook = load_workbook(workbook_path, read_only=True, data_only=True)
    sheet = workbook["全部活动通知"]
    entries: list[dict[str, str]] = []
    seen: set[tuple[str, str, str]] = set()

    for row in sheet.iter_rows(min_row=2, values_only=True):
        if not any(row):
            continue
        date_value, stage, camp, period_label, time_label, activity_name, activity_type, _notice = row[:8]
        if stage not in STAGE_TO_MAJOR:
            raise ValueError(f"Unsupported stage: {stage!r}")
        date = normalize_date(date_value)
        minor_camp_match = re.search(r"\d+", str(camp or ""))
        if not minor_camp_match:
            raise ValueError(f"Unsupported camp value: {camp!r}")
        minor_camp = f"Camp {int(minor_camp_match.group(0))}"
        major_level = STAGE_TO_MAJOR[str(stage)]
        key = (date, major_level, minor_camp)
        if key in seen:
            raise ValueError(f"Duplicate activity key: {key}")
        seen.add(key)
        entries.append({
            "date": date,
            "majorLevel": major_level,
            "minorCamp": minor_camp,
            "periodLabel": str(period_label or "").strip(),
            "time": str(time_label or "").strip(),
            "activityName": str(activity_name or "").strip(),
            "activityType": str(activity_type or "").strip(),
        })

    entries.sort(key=lambda item: (
        item["date"],
        item["majorLevel"],
        int(re.search(r"\d+", item["minorCamp"]).group(0)),
    ))
    return entries


def ts_string(value: object) -> str:
    return json.dumps(value, ensure_ascii=False)


def write_ts(output_path: Path, notices: dict[str, str], entries: list[dict[str, str]]) -> None:
    lines: list[str] = []
    lines.append("// Generated by tools/generate-camp-activity-notices.py from 26苦令营_真实课表_含活动通知话术.xlsx.")
    lines.append("import type { CampMajorLevel } from './campReportCatalog';")
    lines.append("")
    lines.append("export interface CampActivityNoticeEntry {")
    lines.append("  date: string;")
    lines.append("  majorLevel: CampMajorLevel;")
    lines.append("  minorCamp: string;")
    lines.append("  periodLabel: string;")
    lines.append("  time: string;")
    lines.append("  activityName: string;")
    lines.append("  activityType: string;")
    lines.append("}")
    lines.append("")
    lines.append("export const CAMP_ACTIVITY_NOTICE_TEXT: Record<string, string> = {")
    for name in sorted(notices):
        lines.append(f"  {ts_string(name)}: {ts_string(notices[name])},")
    lines.append("};")
    lines.append("")
    lines.append("export const CAMP_ACTIVITY_NOTICE_ALIASES: Record<string, string> = {")
    for source, target in sorted(NOTICE_ALIASES.items()):
        lines.append(f"  {ts_string(source)}: {ts_string(target)},")
    lines.append("};")
    lines.append("")
    lines.append("export const CAMP_ACTIVITY_NOTICE_ENTRIES = [")
    for entry in entries:
        lines.append("  {")
        for key in ["date", "majorLevel", "minorCamp", "periodLabel", "time", "activityName", "activityType"]:
            lines.append(f"    {key}: {ts_string(entry[key])},")
        lines.append("  },")
    lines.append("] as const satisfies readonly CampActivityNoticeEntry[];")
    lines.append("")
    output_path.write_text("\n".join(lines), encoding="utf-8")


def main() -> None:
    parser = argparse.ArgumentParser()
    parser.add_argument("workbook", type=Path)
    parser.add_argument(
        "--output",
        type=Path,
        default=Path("frontend/src/data/campActivityNotices.ts"),
    )
    args = parser.parse_args()

    notices = read_notice_library(args.workbook)
    entries = read_activity_entries(args.workbook)
    write_ts(args.output, notices, entries)
    print(f"Wrote {len(entries)} activity entries and {len(notices)} notices to {args.output}")


if __name__ == "__main__":
    main()
